def read(rel):
    with open(os.path.join(ROOT, rel), encoding="utf-8") as f:
        return f.read()


# ---------------------------------------------------------------------------
# Text helpers
# ---------------------------------------------------------------------------

def esc(text):
    """Escape text for a Markdown table cell."""
    text = " ".join(str(text).split())
    text = text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    for ch in "\\`*_[]{}|":
        text = text.replace(ch, "\\" + ch)
    return text


def esc_multi(text):
    """Like esc, but keep the line breaks of a multi-line text as <br>."""
    lines = [" ".join(l.split()) for l in str(text).strip().split("\n")]
    return "<br>".join(esc(l) for l in lines)


def code(text):
    text = str(text)
    if "`" in text or "|" in text or "\n" in text:
        raise SystemExit("value with a backtick, bar or newline: " + repr(text))
    return "`" + text + "`"


def bits(hi, lo):
    return str(hi) if hi == lo else "%d:%d" % (hi, lo)


def table(header, rows, align=None):
    align = align or ["---"] * len(header)
    out = ["| " + " | ".join(header) + " |", "| " + " | ".join(align) + " |"]
    for row in rows:
        out.append("| " + " | ".join(row) + " |")
    return "\n".join(out) + "\n"


def kv_table(rows):
    out = ["| | |", "|---|---|"]
    for key, value in rows:
        out.append("| %s | %s |" % (key, value))
    return "\n".join(out) + "\n"


def fence(text, lang=""):
    longest = max([len(m) for m in re.findall(r"`+", text)] + [2])
    ticks = "`" * (longest + 1)
    return "%s%s\n%s\n%s\n" % (ticks, lang, text.rstrip("\n"), ticks)


def file_header_comment(rel):
    """The block of '#' lines at the top of a file, without the '#'."""
    lines = []
    for line in read(rel).split("\n"):
        if line.startswith("#"):
            lines.append(line[1:][1:] if line.startswith("# ") else line[1:])
        elif line.strip() == "" and not lines:
            continue
        else:
            break
    return "\n".join(lines).strip("\n")



def tools_page():
    out = [BANNER, "# Tools\n\n",
           "The scripts in `tools/`. The text of each section is the docstring at the top of the script.\n\n"]
    for path in sorted(glob.glob(os.path.join(ROOT, "tools", "*.py"))):
        rel = "tools/" + os.path.basename(path)
        if os.path.basename(path) == "gen_docs.py":
            continue
        doc = ast.get_docstring(ast.parse(read(rel)))
        out.append("## %s\n\n[Source](%s/%s)\n\n" % (code(os.path.basename(path)), GH, rel))
        out.append(fence(doc, "text") + "\n" if doc else "")
    return "".join(out)



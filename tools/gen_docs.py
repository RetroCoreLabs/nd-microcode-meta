def exported_names():
    """From index.ts: {module: None (all exports) or set of names}, in order of appearance."""
    src = read("lib/ts/src/index.ts")
    mods = {}
    for m in re.finditer(r'export\s+(type\s+)?(\*|\{([^}]*)\})\s+from\s+"\./([\w-]+)\.js"', src):
        names, mod = m.group(3), m.group(4)
        if m.group(2) == "*":
            mods[mod] = None
        else:
            wanted = {n.strip().split(" as ")[0].strip() for n in names.split(",") if n.strip()}
            if mods.get(mod, set()) is None:
                continue
            mods.setdefault(mod, set()).update(wanted)
    return mods


def module_header(lines):
    for i, line in enumerate(lines):
        if line.startswith("/**"):
            j = i
            while "*/" not in lines[j]:
                j += 1
            return clean_comment(lines[i:j + 1]), j
        if line.strip() and not line.startswith("//"):
            break
    return "", -1


def clean_comment(block):
    out = []
    for line in block:
        t = line.strip()
        t = t[3:] if t.startswith("/**") else t
        t = t[:-2] if t.endswith("*/") else t
        t = t.lstrip("*")
        t = t[1:] if t.startswith(" ") else t
        out.append(t.rstrip())
    return "\n".join(out).strip("\n")


EXPORT_RE = re.compile(r"^export\s+(?:declare\s+)?(?:async\s+)?(function|const|let|interface|type|class|enum)\s+(\w+)")


def parse_module(rel):
    lines = read(rel).split("\n")
    header, header_end = module_header(lines)
    symbols = []
    for i, line in enumerate(lines):
        m = EXPORT_RE.match(line)
        if not m:
            continue
        kind, name = m.group(1), m.group(2)
        # doc comment directly above
        doc = ""
        k = i - 1
        if k >= 0 and lines[k].strip().endswith("*/"):
            e = k
            while k >= 0 and not lines[k].lstrip().startswith("/**"):
                k -= 1
            doc = clean_comment(lines[k:e + 1])
        # declaration text
        if kind in ("interface", "class", "enum"):
            j = i
            while j < len(lines) and lines[j].rstrip() != "}" and not (j == i and lines[j].rstrip().endswith("}")):
                j += 1
            decl = "\n".join(lines[i:j + 1])
        elif kind == "type":
            j = i
            while not lines[j].rstrip().endswith(";"):
                j += 1
            decl = "\n".join(lines[i:j + 1])
        else:
            j = i
            while j < len(lines) and not re.search(r"(\{\s*$|;\s*$|=\s*$|=>\s*$|=\s*\S.*$)", lines[j]):
                j += 1
            seg = lines[i:j + 1]
            decl = "\n".join(seg)
            decl = re.sub(r"\s*\{\s*$", "", decl)
            if kind in ("const", "let"):
                decl = re.split(r"\s=\s?", decl, 1)[0] + " = ..." if "=" in decl else decl
        symbols.append({"kind": kind, "name": name, "doc": doc, "decl": decl, "line": i + 1})
    return header, symbols


def api_pages(names_by_module):
    pages = {}
    index_rows = []
    for mod, wanted in names_by_module.items():
        rel = "lib/ts/src/%s.ts" % mod
        header, symbols = parse_module(rel)
        if wanted is not None:
            symbols = [s for s in symbols if s["name"] in wanted]
            missing = wanted - {s["name"] for s in symbols}
            if missing:
                print("note: %s: exported by index.ts but no declaration found for: %s"
                      % (rel, ", ".join(sorted(missing))), file=sys.stderr)
        out = [BANNER, "# %s\n\n" % (mod + ".ts"),
               "Source: [`%s`](%s/%s).\n\n" % (rel, GH, rel)]
        if header:
            out.append(fence(header, "text") + "\n")
        if symbols:
            out.append("## Exports\n\n")
            out.append(table(["Name", "Kind"], [["[%s](#%s)" % (code(s["name"]), s["name"].lower()), s["kind"]]
                                               for s in symbols]))
        for s in symbols:
            out.append("\n## %s\n\n" % s["name"])
            if s["doc"]:
                out.append(fence(s["doc"], "text") + "\n")
            out.append(fence(s["decl"], "typescript"))
            out.append("\n[Source line %d](%s/%s#L%d)\n" % (s["line"], GH, rel, s["line"]))
        pages["docs/api/%s.md" % mod] = "".join(out)
        first = header.split("\n")[0] if header else ""
        index_rows.append(["[%s](%s.md)" % (code(mod + ".ts"), mod), str(len(symbols)), esc(first)])
    idx = [BANNER, "# Library API\n\n",
           "The public API of `@nd100uc/microcode` (`lib/ts`), as `src/index.ts` exports it. "
           "Each page shows the header comment of a source file, then every exported name with its "
           "comment and declaration. See [Using the library](../library.md) for how to start.\n\n"]
    idx.append(table(["Module", "Exports", "First line of its comment"], index_rows, ["---", "---:", "---"]))
    pages["docs/api/index.md"] = "".join(idx)
    return pages



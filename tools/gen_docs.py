ACRONYMS = {"alu", "aluf", "alud", "alum", "idbs", "comm", "tsel", "mis", "ldir", "irqno", "idb", "nd100", "nd110",
            "nd120", "vect", "mapj", "slwcs"}


def pretty(key):
    """A heading from a YAML key: 'aluf_formulas' -> 'ALUF formulas'."""
    words = str(key).split("_")
    words = [w.upper() if w.lower() in ACRONYMS else w for w in words]
    text = " ".join(words)
    return text[0].upper() + text[1:] if text and text[0].islower() else text


def scalar(v):
    if v is None:
        return ""
    if isinstance(v, bool):
        return "yes" if v else "no"
    if isinstance(v, list):
        return ", ".join(str(x) for x in v)
    return str(v)


def is_scalar(v):
    return not isinstance(v, (dict, list)) or (isinstance(v, list) and all(not isinstance(x, (dict, list)) for x in v))


def render_value(value, level):
    """Markdown for one YAML value; level is the heading level for sub-sections."""
    if is_scalar(value):
        text = scalar(value)
        return (esc_multi(text) + "\n\n") if "\n" not in text.strip() else fence(text.strip("\n"), "text") + "\n"
    if isinstance(value, dict) and all(is_scalar(v) for v in value.values()):
        rows = [[code(k) if "`" not in str(k) and "|" not in str(k) else esc(k), esc_multi(scalar(v))]
                for k, v in value.items()]
        return table(["Key", "Value"], rows) + "\n"
    if isinstance(value, dict) and all(isinstance(v, dict) and all(is_scalar(x) for x in v.values())
                                       for v in value.values()):
        cols = []
        for v in value.values():
            for k in v:
                if k not in cols:
                    cols.append(k)
        rows = [[code(k) if "`" not in str(k) and "|" not in str(k) else esc(k)] +
                [esc_multi(scalar(v.get(c))) if c in v else "" for c in cols] for k, v in value.items()]
        return table(["Key"] + [esc(c) for c in cols], rows) + "\n"
    if isinstance(value, list) and value and all(isinstance(v, dict) and all(is_scalar(x) for x in v.values())
                                                 for v in value):
        cols = []
        for v in value:
            for k in v:
                if k not in cols:
                    cols.append(k)
        rows = [[esc_multi(scalar(v.get(c))) if c in v else "" for c in cols] for v in value]
        return table([esc(c) for c in cols], rows) + "\n"
    if isinstance(value, dict):
        out = ""
        simple = {k: v for k, v in value.items() if is_scalar(v)}
        if simple:
            out += render_value(simple, level)
        mark = "#" * min(level, 6)
        for k, v in value.items():
            if not is_scalar(v):
                out += "%s %s\n\n%s" % (mark, pretty(k), render_value(v, level + 1))
        return out
    return fence(yaml.safe_dump(value, sort_keys=False, default_flow_style=False, width=100), "yaml") + "\n"


def yaml_page(title, lead, rels):
    out = [BANNER, "# %s\n\n" % title, lead + "\n\n"]
    for rel in rels:
        doc = load_yaml(rel)
        out.append("Source: [`%s`](%s/%s).\n\n" % (rel, GH, rel))
        head = file_header_comment(rel)
        if head:
            out.append("## Header of `%s`\n\n" % os.path.basename(rel) + fence(head, "text") + "\n")
        for key, value in doc.items():
            out.append("## %s\n\n%s" % (pretty(key), render_value(value, 3)))
    return "".join(out)



def tracked(rel):
    try:
        out = subprocess.run(["git", "ls-files", "--cached", "--others", "--exclude-standard", "--", rel],
                             cwd=ROOT, capture_output=True, text=True, check=True).stdout
        return rel in out.split("\n")
    except (OSError, subprocess.CalledProcessError):
        return os.path.exists(os.path.join(ROOT, rel))


def page_title(rel):
    for line in read(rel).split("\n"):
        if line.startswith("# "):
            return line[2:].strip()
    return os.path.basename(rel)


def build_nav(names, docs, api_modules, generated):
    items = [{"Home": "index.md"}]
    for g in GUIDES:
        if tracked(g):
            items.append({page_title(g): g})
    variants = [{"Overview": "docs/variants/index.md"}]
    for n in names:
        title = "ND-120 (version L)" if n == "nd120-dly" else docs[n]["model"]
        variants.append({title: "docs/variants/%s.md" % n})
    items.append({"Variants": variants})
    items.append({"Definitions": [
        {"Data flow": "docs/definitions/data-flow.md"},
        {"Registers and conditions": "docs/definitions/registers-and-conditions.md"},
        {"Assembly format": "docs/definitions/assembly-format.md"},
    ]})
    items.append({"Library API": [{"Overview": "docs/api/index.md"}] +
                  [{m + ".ts": "docs/api/%s.md" % m} for m in api_modules]})
    items.append({"Tools": "docs/tools.md"})
    hw = [{page_title(h): h} for h in HARDWARE if tracked(h)]
    items.append({"Hardware and reference": hw})
    known = set(GUIDES) | set(HARDWARE) | set(generated)
    others = sorted("docs/" + f for f in os.listdir(os.path.join(ROOT, "docs"))
                    if f.endswith(".md") and "docs/" + f not in known and tracked("docs/" + f))
    for o in others:
        items.append({page_title(o): o})
    if tracked("CHANGELOG.md"):
        items.append({"Changelog": "CHANGELOG.md"})
    return items



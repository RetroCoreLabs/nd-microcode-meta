#!/usr/bin/env python3
"""Make the generated part of the documentation site.

Writes:
  docs/variants/index.md, docs/variants/<name>.md
                         one page per variant: fields and the groups of mnemonics
  docs/definitions/data-flow.md, registers-and-conditions.md, assembly-format.md
                         the YAML files of defs/runtime, defs/common, defs/format as tables
  docs/api/index.md, docs/api/<module>.md
                         the public API of lib/ts, taken from the TypeScript source
  docs/tools.md          the scripts in tools/, taken from their docstrings
  docs-site/mkdocs.yml   the navigation (inherits docs-site/base.yml)

Everything comes from files in this repository. Nothing is typed in here.

Run from anywhere:
  python3 tools/gen_docs.py            write the files
  python3 tools/gen_docs.py --check    write nothing; exit 1 if a file would change

The hand-written pages (index.md, CHANGELOG.md, the other pages in docs/ and
reference/) are not touched.
"""


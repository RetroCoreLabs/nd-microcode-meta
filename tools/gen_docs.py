def main():
    check = "--check" in sys.argv[1:]
    names = variant_names()
    tokens_docs, fields_docs = {}, {}
    for n in names:
        if n == "nd120-dly":
            continue
        tokens_docs[n] = load_yaml("defs/tokens/%s-tokens.yaml" % n)
        fp = "defs/fields/%s-fields.yaml" % n
        fields_docs[n] = load_yaml(fp) if os.path.exists(os.path.join(ROOT, fp)) else None

    files = {}
    for n in names:
        if n == "nd120-dly":
            files["docs/variants/nd120-dly.md"] = dly_page(tokens_docs["nd120"])
        else:
            files["docs/variants/%s.md" % n] = variant_page(n, tokens_docs[n], fields_docs[n], None)
    files["docs/variants/index.md"] = variants_index(names, tokens_docs)

    files["docs/definitions/data-flow.md"] = yaml_page(
        "Data flow",
        "How the ND-100, ND-110 and ND-120 execute an instruction: where the ALU gets its operands, what the "
        "destinations do, the sources of the internal data bus and the effects of the commands.",
        ["defs/runtime/data-flow.yaml"])
    files["docs/definitions/registers-and-conditions.md"] = yaml_page(
        "Registers and conditions",
        "Register names and condition names shared by ND-100, ND-110 and ND-120.",
        ["defs/common/registers.yaml", "defs/common/conditions.yaml"])
    files["docs/definitions/assembly-format.md"] = yaml_page(
        "Assembly format",
        "How a microinstruction of the ND-100, ND-110 and ND-120 is written as text.",
        ["defs/format/assembly-format.yaml"])

    mods = exported_names()
    files.update(api_pages(mods))
    files["docs/tools.md"] = tools_page()

    header = ("# Made by tools/gen_docs.py. Do not edit; change docs-site/base.yml or the script.\n"
              "# Navigation of the documentation site.\nINHERIT: base.yml\n\n")
    files["docs-site/mkdocs.yml"] = header + yaml.safe_dump(
        {"nav": build_nav(names, tokens_docs, list(mods.keys()), [k for k in files if k.endswith(".md")])},
        sort_keys=False, allow_unicode=False, default_flow_style=False, width=1000)

    changed = []
    for rel, text in files.items():
        path = os.path.join(ROOT, rel)
        old = None
        if os.path.exists(path):
            with open(path, encoding="utf-8", newline="") as f:
                old = f.read()
        if old != text:
            changed.append(rel)
            if not check:
                os.makedirs(os.path.dirname(path), exist_ok=True)
                with open(path, "w", encoding="utf-8", newline="\n") as f:
                    f.write(text)
    if check:
        for rel in changed:
            print("out of date:", rel, file=sys.stderr)
        if changed:
            print("run: python3 tools/gen_docs.py", file=sys.stderr)
            return 1
        print("generated pages are up to date (%d files)" % len(files))
        return 0
    print("wrote %d files, %d changed" % (len(files), len(changed)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
